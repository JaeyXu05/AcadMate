def _report_snapshot(
    events: list[dict[str, Any]],
    plans: list[dict[str, Any]],
    chats: list[dict[str, Any]],
    growth: dict[str, Any],
    profile: dict[str, Any],
) -> tuple[dict[str, Any], list[str]]:
    """Build a compact, user-facing source packet instead of raw DB fields."""

    refs: list[str] = []
    event_rows: list[dict[str, Any]] = []
    ordered_events = sorted(events, key=lambda item: str(item.get("created_at") or ""))
    # Reports need representative facts, not every workflow heartbeat.  Keeping
    # this packet compact materially reduces first-token latency on the shared
    # CHATAGENT endpoint while preserving recent, auditable evidence.
    for index, item in enumerate(ordered_events[-20:], start=1):
        object_type = str(item.get("object_type") or "activity")
        object_id = str(item.get("object_id") or index)
        source_ref = f"activity:{object_type}:{object_id}"
        refs.append(source_ref)
        event_rows.append(
            {
                "记录编号": source_ref,
                "时间": item.get("created_at"),
                "动作": item.get("verb"),
                "对象": object_type,
                "结果": _compact_value(item.get("result") or {}),
                "证据": list(item.get("evidence_refs") or [])[:6],
            }
        )

    plan_rows: list[dict[str, Any]] = []
    for index, item in enumerate(plans[:12], start=1):
        source_ref = f"plan:{item.get('id') or index}"
        refs.append(source_ref)
        plan_rows.append(
            {
                "记录编号": source_ref,
                "计划名称": str(item.get("title") or "")[:240],
                "计划说明": str(item.get("description") or "")[:500],
                "状态": item.get("status"),
                "优先级": item.get("priority"),
                "开始时间": item.get("start_at"),
                "截止时间": item.get("due_at"),
                "预计分钟": item.get("estimated_minutes"),
                "实际分钟": item.get("actual_minutes"),
                "完成反馈": str(item.get("execution_notes") or "")[:800],
                "完成时间": item.get("completed_at"),
            }
        )

    chat_rows: list[dict[str, Any]] = []
    for index, item in enumerate(chats[-12:], start=1):
        content = _clean_chat_content(str(item.get("content") or ""))
        if not content:
            continue
        source_ref = f"chat:{str(item.get('created_at') or index).replace(' ', 'T')}"
        refs.append(source_ref)
        chat_rows.append(
            {
                "记录编号": source_ref,
                "参与者": item.get("role"),
                "时间": item.get("created_at"),
                "内容": content[:700],
            }
        )

    background_rows = {
        "研究方向": _compact_value(growth.get("directions") or []),
        "导师匹配": _compact_value(growth.get("matched_mentors") or []),
        "论文阅读": _compact_value(growth.get("read_papers") or []),
        "研究任务": _compact_value(growth.get("research_tasks") or []),
        "已核验经历": _compact_value(
            growth.get("verified_experiences") or []
        ),
    }
    user_profile = {
        "研究阶段": profile.get("grade") or "",
        "专业": profile.get("major") or "",
        "研究兴趣": _compact_value(profile.get("interests") or []),
        "已有技能": _compact_value(profile.get("skills") or []),
        "补充说明": str(profile.get("bio") or "")[:500],
    }
    return {
        "本周期科研活动": event_rows,
        "本周期计划与状态": plan_rows,
        "近期讨论": chat_rows,
        "研究背景": background_rows,
        "用户学习背景": user_profile,
    }, list(dict.fromkeys(refs))


