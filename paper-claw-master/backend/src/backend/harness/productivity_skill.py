def _parse_local_datetime(value: str | None) -> datetime | None:
    text = str(value or "").strip()
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is not None:
        return parsed.astimezone(UTC).replace(tzinfo=None)
    return parsed


def _format_local_datetime(value: datetime) -> str:
    return value.strftime("%Y-%m-%dT%H:%M")


def _normalize_report_action_dates(
    draft: ProgressReportDraft,
    *,
    period_end: str,
    current_time: str,
) -> ProgressReportDraft:
    """Prevent a model from proposing already-expired dates in next actions."""

    normalized = draft.model_copy(deep=True)
    floor = _parse_local_datetime(current_time) or _parse_local_datetime(period_end)
    if floor is None:
        return normalized
    for item in normalized.next_actions:
        proposed = _parse_local_datetime(item.target_date)
        if proposed is None or proposed.date() < floor.date():
            item.target_date = floor.strftime("%Y-%m-%d")
    return normalized


def _restrict_evidence_refs(
    draft: ProgressReportDraft, allowed: set[str]
) -> ProgressReportDraft:
    cleaned = draft.model_copy(deep=True)
    for item in [
        *cleaned.completed_work,
        *cleaned.work_in_progress,
        *cleaned.discussion_insights,
        *cleaned.blockers,
        *cleaned.next_actions,
    ]:
        item.evidence_refs = list(
            dict.fromkeys(ref for ref in item.evidence_refs if ref in allowed)
        )
    return cleaned


def _render_progress_markdown(
    title: str,
    period: str,
    metrics: dict[str, int],
    draft: ProgressReportDraft,
) -> str:
    completion_feedbacks = int(metrics.get("completion_feedbacks") or 0)
    cycle = {"daily": "本日", "weekly": "本周", "monthly": "本月"}.get(
        period, "本周期"
    )
    lines = [
        f"# {title}",
        "",
        "## 一、执行摘要",
        draft.executive_summary.strip(),
        "",
        "## 二、进展判断",
        draft.progress_assessment.strip(),
        "",
        "## 三、已完成工作与产出",
    ]
    if draft.completed_work:
        for item in draft.completed_work:
            lines.extend(
                [
                    f"### {item.title}",
                    f"- 事实：{item.fact}",
                    f"- 意义：{item.significance}",
                    f"- 依据：{_refs(item.evidence_refs)}",
                ]
            )
    else:
        lines.append("- 本周期暂无可核验的完成项。")

    lines.extend(["", "## 四、进行中工作"])
    no_verified_execution = draft.work_in_progress and all(
        "尚未记录可核验" in item.fact for item in draft.work_in_progress
    )
    if no_verified_execution:
        lines.append(
            f"- 当前有 {metrics['pending_plans']} 项开放计划，但本周期尚无可核验的执行结果；"
            "计划状态和时间预算请结合下方量化记录与计划页查看。"
        )
    elif draft.work_in_progress:
        for item in draft.work_in_progress[:2]:
            lines.extend(
                [
                    f"### {item.title}",
                    f"- {item.fact}",
                    f"- 研究含义：{item.significance}",
                    f"- 依据：{_refs(item.evidence_refs)}",
                ]
            )
    else:
        lines.append("- 当前没有足够记录支持进行中事项判断。")

    lines.extend(["", "## 五、问题、阻塞与风险"])
    if draft.blockers:
        for item in draft.blockers:
            lines.extend(
                [
                    f"- **问题：** {item.issue}",
                    f"  - 影响：{item.impact}",
                    f"  - 处理建议：{item.proposed_resolution}",
                    f"  - 依据：{_refs(item.evidence_refs)}",
                ]
            )
    else:
        lines.append("- 记录中没有明确阻塞；这不等同于实际不存在阻塞。")
    lines.extend(f"- 风险：{risk}" for risk in draft.risks[:6])

    lines.extend(["", "## 六、讨论焦点与形成的判断"])
    if draft.discussion_insights:
        for item in draft.discussion_insights:
            lines.extend(
                [
                    f"- **{item.title}：** {item.fact}",
                    f"  - 科研含义：{item.significance}",
                    f"  - 依据：{_refs(item.evidence_refs)}",
                ]
            )
    else:
        lines.append("- 对话记录尚未形成可核验的研究判断。")

    lines.extend(["", f"## 七、{cycle}后续行动"])
    for index, item in enumerate(draft.next_actions, start=1):
        criteria = "；".join(item.acceptance_criteria)
        deadline = item.target_date or "待结合计划日期确认"
        lines.extend(
            [
                f"{index}. **[{item.priority.upper()}] {item.action}**",
                f"   - 原因：{item.rationale}",
                f"   - 交付物：{item.deliverable}",
                f"   - 验收标准：{criteria}",
                f"   - 目标时间：{deadline}",
                f"   - 依据：{_refs(item.evidence_refs)}",
            ]
        )

    lines.extend(
        [
            "",
            "## 八、量化记录",
            f"- 科研活动记录：{metrics['activity_events']} 条",
            f"- 完成反馈：{completion_feedbacks} 条",
            f"- 完成计划：{metrics['completed_plans']} 项",
            f"- 开放计划：{metrics['pending_plans']} 项",
            f"- 已审核匹配导师：{metrics['matched_mentors']} 位",
            f"- 已记录论文阅读：{metrics['read_papers']} 项",
            "",
            "## 九、信息缺口与数据边界",
        ]
    )
    lines.extend(
        f"- {item}" for item in draft.missing_information[:8]
    )
    if not draft.missing_information:
        lines.append("- 未发现模型需要额外声明的信息缺口。")
    lines.append("- 报告只使用平台内已记录事实；未记录的线下进展不作推断。")
    return _sanitize_report_markdown("\n".join(lines))


def _sanitize_report_markdown(markdown: str) -> str:
    """Keep implementation paths and field labels out of researcher-facing reports."""

    cleaned = _LOCAL_PATH.sub("本地资源", markdown)
    for term in _INTERNAL_TEXT_TERMS:
        cleaned = re.sub(re.escape(term), "平台记录", cleaned, flags=re.IGNORECASE)
    return cleaned


def _review_report(markdown: str, draft: ProgressReportDraft) -> list[str]:
    failed: list[str] = []
    if len(markdown) < 650:
        failed.append("report_too_short")
    if not draft.next_actions:
        failed.append("next_actions_missing")
    if any(not item.acceptance_criteria for item in draft.next_actions):
        failed.append("acceptance_criteria_missing")
    runtime_hits = sum(
        1 for line in markdown.splitlines() if _RUNTIME_LINE.match(line.lstrip("-#* "))
    )
    if runtime_hits >= 2:
        failed.append("runtime_log_leak")
    lowered = markdown.lower()
    if any(term in lowered for term in _INTERNAL_TEXT_TERMS):
        failed.append("internal_field_leak")
    if any(
        _parse_local_datetime(item.target_date)
        and _parse_local_datetime(item.target_date).date() < datetime.now().date()
        for item in draft.next_actions
    ):
        failed.append("past_target_date")
    return failed


def _clean_chat_content(content: str) -> str:
    lines = [
        line.strip()
        for line in content.splitlines()
        if line.strip() and not _RUNTIME_LINE.match(line.strip())
    ]
    return "\n".join(lines)


def _compact_value(value: Any, depth: int = 0) -> Any:
    if depth >= 3:
        return str(value)[:240]
    if isinstance(value, dict):
        return {
            str(key): _compact_value(item, depth + 1)
            for key, item in list(value.items())[:16]
            if str(key) not in {"payload_json", "raw", "content_markdown"}
        }
    if isinstance(value, list):
        return [_compact_value(item, depth + 1) for item in value[:10]]
    if isinstance(value, str):
        return value[:600]
    return value


def _collect_evidence_refs(value: Any) -> list[str]:
    if isinstance(value, dict):
        own = value.get("evidence_refs")
        refs = [str(item) for item in own if str(item)] if isinstance(own, list) else []
        for item in value.values():
            refs.extend(_collect_evidence_refs(item))
        return list(dict.fromkeys(refs))
    if isinstance(value, list):
        refs: list[str] = []
        for item in value:
            refs.extend(_collect_evidence_refs(item))
        return list(dict.fromkeys(refs))
    return []


def _refs(values: list[str]) -> str:
    if not values:
        return "平台记录（无外部证据编号）"
    readable: list[str] = []
    for value in values:
        if value.startswith("plan:"):
            readable.append("计划记录")
        elif value.startswith("activity:"):
            readable.append("科研活动记录")
        elif value.startswith("chat:"):
            readable.append("讨论记录")
        elif value.startswith("paper_chunk:"):
            readable.append("论文证据")
        else:
            readable.append(value)
    return "、".join(dict.fromkeys(readable))


def _persist_progress(
    session: Session,
    request: RunCreate,
    artifact: dict[str, Any],
    evidence_refs: list[str],
    *,
    status: str,
    review_status: str,
    run_id: int | None,
) -> RunCreated:
    output_json = {
        "review_status": review_status,
        "evidence_refs": evidence_refs,
        "artifact": artifact,
    }
    error_message = str(artifact.get("error") or "") or None
    repository = AgentRunRepository(session)
    if run_id is None:
        run = repository.create(
            WorkflowName.progress_report.value,
            status=status,
            input_json={
                "message": request.message,
                "metadata": {
                    "harness_skill_id": "progress_report",
                    "period_type": request.context.report_period or "weekly",
                },
            },
            output_json=output_json,
            error_message=error_message,
        )
    else:
        run = repository.update_status(
            run_id,
            status,
            output_json=output_json,
            error_message=error_message,
        )
    session.commit()
    _record_stage(session, run.id, "completed", 100, "报告已生成，可查看并复核")
    return RunCreated(
        run_id=str(run.id),
        skill_id="progress_report",
        status=run.status,
        review_status=review_status,
        evidence_refs=evidence_refs,
        artifact=artifact,
    )


def _persist(
    session: Session,
    request: RunCreate,
    workflow: str,
    skill_id: str,
    artifact: dict[str, Any],
    evidence_refs: list[str],
    *,
    run_id: int | None = None,
) -> RunCreated:
    repository = AgentRunRepository(session)
    output_json = {"review_status": "PASS", "evidence_refs": evidence_refs, "artifact": artifact}
    if run_id is None:
        run = repository.create(
            workflow,
            status=RunStatus.succeeded.value,
            input_json={"message": request.message, "metadata": {"harness_skill_id": skill_id, **_audit_context(request)}},
            output_json=output_json,
        )
    else:
        run = repository.update_status(run_id, RunStatus.succeeded.value, output_json=output_json)
    session.commit()
    _record_stage(session, run.id, "completed", 100, "计划已生成，可查看阶段拆解与提醒")
    return RunCreated(
        run_id=str(run.id), skill_id=skill_id, status=run.status,
        review_status="PASS", evidence_refs=evidence_refs, artifact=artifact,
    )
