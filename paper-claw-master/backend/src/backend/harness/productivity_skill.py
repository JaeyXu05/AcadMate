class ReportFinding(BaseModel):
    title: str = Field(min_length=1, max_length=120)
    fact: str = Field(min_length=1, max_length=700)
    significance: str = Field(min_length=1, max_length=500)
    evidence_refs: list[str] = Field(default_factory=list)


class ReportBlocker(BaseModel):
    issue: str = Field(min_length=1, max_length=300)
    impact: str = Field(min_length=1, max_length=400)
    proposed_resolution: str = Field(min_length=1, max_length=500)
    evidence_refs: list[str] = Field(default_factory=list)


class ReportAction(BaseModel):
    action: str = Field(min_length=1, max_length=240)
    rationale: str = Field(min_length=1, max_length=400)
    deliverable: str = Field(min_length=1, max_length=300)
    acceptance_criteria: list[str] = Field(min_length=1, max_length=4)
    priority: str = "medium"
    target_date: str | None = None
    evidence_refs: list[str] = Field(default_factory=list)


class ProgressReportDraft(BaseModel):
    executive_summary: str = Field(min_length=40, max_length=1200)
    progress_assessment: str = Field(min_length=20, max_length=1000)
    completed_work: list[ReportFinding] = Field(default_factory=list)
    work_in_progress: list[ReportFinding] = Field(default_factory=list)
    blockers: list[ReportBlocker] = Field(default_factory=list)
    discussion_insights: list[ReportFinding] = Field(default_factory=list)
    next_actions: list[ReportAction] = Field(min_length=1, max_length=6)
    risks: list[str] = Field(default_factory=list)
    missing_information: list[str] = Field(default_factory=list)


class PlanMilestone(BaseModel):
    sequence: int = Field(ge=1, le=12)
    source_plan_id: int | None = None
    title: str = Field(min_length=1, max_length=160)
    objective: str = Field(min_length=1, max_length=600)
    deliverable: str = Field(min_length=1, max_length=300)
    acceptance_criteria: list[str] = Field(min_length=1, max_length=4)
    priority: Literal["low", "medium", "high"] = "medium"
    estimated_minutes: int = Field(ge=15, le=480)
    start_at: str | None = None
    due_at: str | None = None
    reminder_at: str | None = None
    rationale: str = Field(min_length=1, max_length=500)
    evidence_refs: list[str] = Field(default_factory=list)


class PlanCoachDraft(BaseModel):
    planning_summary: str = Field(min_length=30, max_length=900)
    capacity_assessment: str = Field(min_length=20, max_length=700)
    personalization_basis: list[str] = Field(default_factory=list, max_length=6)
    milestones: list[PlanMilestone] = Field(min_length=1, max_length=8)
    risks: list[str] = Field(default_factory=list, max_length=6)


